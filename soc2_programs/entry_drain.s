# ENTRY-DRAIN regression test (Attempt 18 fix): a timer interrupt
# taken to S-mode while a csrrci sstatus sits in MEM at entry must
# leave the entry's SPP=1 intact and return to S-mode.
#
# Shape (the PID 1 panic, miniaturised): S-mode runs with SIE=1
# and a delegated timer tick pending; the tick fires while the
# csrrci below is in MEM. On the UNFIXED core the draining
# csrrci commits one cycle after entry and overwrites the
# entry's sstatus (SPP 1 -> 0); the handler then reads 0x20
# and the test FAILS (s0=1). On the FIXED core the conflicting
# MEM drain is suppressed, the handler reads the entry value
# 0x120 (SPP=1, SPIE=1, SIE=0), and the test PASSES (s0=0).
#
# The handler also records sepc: at a true MEM-alignment entry
# sepc is the instruction two past the csrrci (the ID-stage
# instruction at entry). If sepc differs, the interrupt did not
# land on the csrrci and the run is a calibration MISS (s0=2),
# not a pass or a bug -- the PAD below was calibrated so the
# tick lands exactly on the csrrci (see tools/entry_drain_cal.py).
#
# Expected footer on the fixed core: halted=1, s0=0,
# s1=0x120, s2=drain+8, s3=1.
# Runs bare in M-mode from RAM base (soc2 harness, like the
# fault_spp tests); drops to S via mret. No translation, no
# SBI, no rootfs. Integrated into tools/soc2_check.py
# (a0 = s0 at halt, so the standard a0==0 check applies).
start:
    li sp, 0x8000F000
    li s0, 0
    li s1, 0
    li s2, 0
    li s3, 0
    # Delegate the timer interrupt to S (core convention:
    # mideleg bit 7 = timer, cf. firmware mideleg=0x888).
    li t0, 0x80
    csrw mideleg, t0
    # mstatus: MPP=S (01), MPIE=1, so mret drops to S.
    csrr t0, mstatus
    li t1, 0xFFFFE7FF
    and t0, t0, t1
    li t1, 0x800
    or t0, t0, t1
    li t1, 0x80
    or t0, t0, t1
    csrw mstatus, t0
    # CLINT: mtimecmp = mtime + DELTA, so the tick fires a
    # fixed number of cycles after this read. mtime is small
    # here, so lo+DELTA cannot wrap 32 bits.
    li t0, 0x0200BFF8
    lw t1, 0(t0)
    lw t2, 4(t0)
    addi t1, t1, 150
    li t0, 0x02004000
    sw t1, 0(t0)
    sw t2, 4(t0)
    la t0, handler
    csrw stvec, t0
    la t0, s_main
    csrw mepc, t0
    mret
