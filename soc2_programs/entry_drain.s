drain:
    csrrci x0, sstatus, 2   # clear SIE -- the draining instruction
    # Fall through to the wait loop. If the tick fired on
    # `drain`, the handler has already run and set s3; if it
    # fired early (pad) or never (drain committed first),
    # s3/sepc below report the miss.
wait:
    bne s3, x0, verdict
    addi t1, t1, -1
    bne t1, x0, wait
    li s0, 2                # timeout: no interrupt at all
    j halt
verdict:
    la t0, drain
    addi t0, t0, 4          # sepc must be the instruction
    bne s2, t0, miss        # after drain: at entry, drain
                            # is in EX (advancing to MEM at
                            # the entry edge) and ID holds
                            # the next instruction, which
                            # the entry saves as sepc
                            # (trace-verified, pads 121-123)
    srli t0, s1, 8
    andi t0, t0, 1          # SPP bit
    beq t0, x0, bug         # SPP=0: entry clobbered
    li s0, 0                # SPP=1: entry intact
    j halt
bug:
    li s0, 1
    j halt
miss:
    li s0, 2
    j halt
halt:
    mv a0, s0
    ecall                   # mtvec==0, so ecall halts
    j halt
handler:
    csrr t0, sstatus
    mv s1, t0               # sstatus as the handler saw it
    csrr t0, sepc
    mv s2, t0               # interrupted pc
    li s3, 1                # entered
    csrr t0, 0xC00
    mv s4, t0               # core cycle at handler entry
                            # (diagnostic: entry-cycle tracking)
    # Repair: restore a clean entry state (SPP=1, SPIE=0,
    # SIE=0) and return to the wait loop, whether the entry
    # was clean or clobbered. SPIE must be 0 here: sret
    # copies SPIE to SIE, so a repair of 0x120 would
    # re-enable interrupts on return and, with the tick
    # still pending, loop the handler forever.
    li t0, 0x100
    csrw sstatus, t0
    la t0, wait
    csrw sepc, t0
    sret
